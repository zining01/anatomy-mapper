// Geometry helpers used to build the artwork and the clickable regions.
//
// Every outline is a list of [x, y] points in SVG user units. Smooth curves are
// produced with a centripetal Catmull–Rom spline that passes *through* its
// control points, so a junction point shared by two curves is reproduced
// exactly in both. Regions are then assembled from pieces of those curves,
// which keeps neighbouring subunits gap-free and overlap-free.

const round = (v) => Math.round(v * 10) / 10;
const same = (a, b) => Math.abs(a[0] - b[0]) < 0.01 && Math.abs(a[1] - b[1]) < 0.01;

/** Smooth curve through `pts`. Returns a dense point list (control points included). */
export function spline(pts, { closed = false, steps = 8 } = {}) {
  const n = pts.length;
  if (n < 3 && !closed) return pts.map((p) => [p[0], p[1]]);
  const get = (i) => {
    if (closed) return pts[((i % n) + n) % n];
    if (i < 0) return [2 * pts[0][0] - pts[1][0], 2 * pts[0][1] - pts[1][1]];
    if (i >= n) return [2 * pts[n - 1][0] - pts[n - 2][0], 2 * pts[n - 1][1] - pts[n - 2][1]];
    return pts[i];
  };
  const out = [];
  const segs = closed ? n : n - 1;
  for (let i = 0; i < segs; i++) {
    const p0 = get(i - 1), p1 = get(i), p2 = get(i + 1), p3 = get(i + 2);
    for (let s = 0; s < steps; s++) out.push(s === 0 ? [p1[0], p1[1]] : catmullRom(p0, p1, p2, p3, s / steps));
  }
  if (!closed) out.push([pts[n - 1][0], pts[n - 1][1]]);
  return out;
}

function catmullRom(p0, p1, p2, p3, u) {
  const dt = (a, b) => Math.max(Math.pow(Math.hypot(b[0] - a[0], b[1] - a[1]), 0.5), 1e-4);
  const t0 = 0, t1 = t0 + dt(p0, p1), t2 = t1 + dt(p1, p2), t3 = t2 + dt(p2, p3);
  const t = t1 + (t2 - t1) * u;
  const mix = (a, b, ta, tb) => {
    const w = (t - ta) / (tb - ta);
    return [a[0] + (b[0] - a[0]) * w, a[1] + (b[1] - a[1]) * w];
  };
  const a1 = mix(p0, p1, t0, t1), a2 = mix(p1, p2, t1, t2), a3 = mix(p2, p3, t2, t3);
  const b1 = mix(a1, a2, t0, t2), b2 = mix(a2, a3, t1, t3);
  return mix(b1, b2, t1, t2);
}

export const rev = (pts) => pts.slice().reverse();

/** Concatenate point lists, dropping the duplicated point where pieces meet. */
export function chain(...parts) {
  const out = [];
  for (const part of parts)
    for (const p of part) if (!out.length || !same(out[out.length - 1], p)) out.push(p);
  if (out.length > 1 && same(out[0], out[out.length - 1])) out.pop();
  return out;
}

function nearestIndex(pts, q) {
  let best = 0, bd = Infinity;
  pts.forEach((p, i) => {
    const d = (p[0] - q[0]) ** 2 + (p[1] - q[1]) ** 2;
    if (d < bd) { bd = d; best = i; }
  });
  return best;
}

/** The part of curve `pts` running from the sample nearest `a` to the sample nearest `b`. */
export function seg(pts, a, b) {
  const i = nearestIndex(pts, a), j = nearestIndex(pts, b);
  return i <= j ? pts.slice(i, j + 1) : pts.slice(j, i + 1).reverse();
}

/** SVG path data for a point list. */
export const pathD = (pts, closed = true) =>
  "M" + pts.map((p) => round(p[0]) + " " + round(p[1])).join("L") + (closed ? "Z" : "");

export const mirror = (pts, cx) => pts.map(([x, y]) => [2 * cx - x, y]);

/**
 * Close a region that sits on the vertical midline. `half` runs from a point on
 * the midline, around one side, back to another point on the midline; the other
 * side is generated by mirroring.
 */
export const midline = (half, cx) => chain(half, rev(mirror(half, cx)));

/**
 * A 2-D frame for a limb: local x across the limb (negative = lateral,
 * positive = medial), local y along it from `origin`. `angle` in degrees.
 * With `mirrorCx`, the frame is reflected about x = mirrorCx (the other side).
 */
export function frame({ origin, angle = 0, mirrorCx = null }) {
  const a = (angle * Math.PI) / 180, c = Math.cos(a), s = Math.sin(a);
  return (pts) =>
    pts.map(([lx, ly]) => {
      const x = origin[0] + lx * c - ly * s;
      const y = origin[1] + lx * s + ly * c;
      return mirrorCx == null ? [x, y] : [2 * mirrorCx - x, y];
    });
}

/** Approximate "pole of inaccessibility": the interior point farthest from the edges. */
export function labelPoint(pts) {
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  for (const [x, y] of pts) {
    minX = Math.min(minX, x); minY = Math.min(minY, y);
    maxX = Math.max(maxX, x); maxY = Math.max(maxY, y);
  }
  const score = (x, y) => (inside(pts, x, y) ? edgeDistance(pts, x, y) : -1);
  let best = [(minX + maxX) / 2, (minY + maxY) / 2], bestScore = score(...best);
  let step = Math.max(maxX - minX, maxY - minY) / 16;
  for (let x = minX; x <= maxX; x += step)
    for (let y = minY; y <= maxY; y += step) {
      const s = score(x, y);
      if (s > bestScore) { bestScore = s; best = [x, y]; }
    }
  for (let k = 0; k < 4; k++) {
    step /= 3;
    const [cx, cy] = best;
    for (let i = -3; i <= 3; i++)
      for (let j = -3; j <= 3; j++) {
        const s = score(cx + i * step, cy + j * step);
        if (s > bestScore) { bestScore = s; best = [cx + i * step, cy + j * step]; }
      }
  }
  return [round(best[0]), round(best[1])];
}

/** Best label point constrained to the vertical line x (for midline regions). */
export function labelPointOnLine(pts, x) {
  const ys = pts.map((p) => p[1]);
  const lo = Math.min(...ys), hi = Math.max(...ys);
  let best = (lo + hi) / 2, bestScore = -1;
  for (let y = lo; y <= hi; y += (hi - lo) / 200) {
    const s = inside(pts, x, y) ? edgeDistance(pts, x, y) : -1;
    if (s > bestScore) { bestScore = s; best = y; }
  }
  return [round(x), round(best)];
}

function inside(pts, x, y) {
  let hit = false;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
    const [xi, yi] = pts[i], [xj, yj] = pts[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

function edgeDistance(pts, x, y) {
  let d = Infinity;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
    const [ax, ay] = pts[j], [bx, by] = pts[i];
    const dx = bx - ax, dy = by - ay;
    const t = Math.max(0, Math.min(1, ((x - ax) * dx + (y - ay) * dy) / (dx * dx + dy * dy || 1)));
    d = Math.min(d, Math.hypot(x - ax - t * dx, y - ay - t * dy));
  }
  return d;
}
